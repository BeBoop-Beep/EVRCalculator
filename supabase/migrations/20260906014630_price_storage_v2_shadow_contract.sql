-- Canonical steady-state contract for Price Storage V2 shadow infrastructure.
-- This migration is intentionally idempotent so it can safely reconcile an
-- environment where the remote-history bridge migrations were already applied.
-- It does NOT switch production readers and does NOT delete legacy history.

BEGIN;

CREATE TABLE IF NOT EXISTS public.card_variant_price_events_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_variant_id uuid NOT NULL REFERENCES public.card_variants(id) ON DELETE CASCADE,
    condition_id uuid NOT NULL REFERENCES public.conditions(id),
    source text NOT NULL,
    currency text NOT NULL,
    effective_date date NOT NULL,
    event_type text NOT NULL CHECK (event_type IN ('PRICE','UNPRICED','RETURNED_TO_MARKET','RETIRED')),
    market_price numeric,
    high_price numeric,
    low_price numeric,
    source_observation_id uuid,
    source_created_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT card_variant_price_events_v2_day_unique
        UNIQUE (card_variant_id, condition_id, source, currency, effective_date),
    CONSTRAINT card_variant_price_events_v2_price_state_check CHECK (
        (event_type IN ('PRICE','RETURNED_TO_MARKET') AND market_price IS NOT NULL)
        OR (event_type IN ('UNPRICED','RETIRED') AND market_price IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.card_variant_price_current_v2 (
    card_variant_id uuid NOT NULL REFERENCES public.card_variants(id) ON DELETE CASCADE,
    condition_id uuid NOT NULL REFERENCES public.conditions(id),
    source text NOT NULL,
    currency text NOT NULL,
    event_id bigint NOT NULL REFERENCES public.card_variant_price_events_v2(id) ON DELETE CASCADE,
    effective_date date NOT NULL,
    state text NOT NULL CHECK (state IN ('PRICE','UNPRICED','RETURNED_TO_MARKET','RETIRED')),
    market_price numeric,
    high_price numeric,
    low_price numeric,
    source_observation_id uuid,
    updated_at timestamptz NOT NULL DEFAULT now(),
    last_observed_date date,
    last_observation_id uuid,
    last_observation_created_at timestamptz,
    PRIMARY KEY (card_variant_id, condition_id, source, currency)
);

CREATE INDEX IF NOT EXISTS card_variant_price_current_v2_event_id_idx
