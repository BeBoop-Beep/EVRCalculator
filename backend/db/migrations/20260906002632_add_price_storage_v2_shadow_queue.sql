CREATE TABLE IF NOT EXISTS public.price_storage_v2_shadow_queue (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id uuid NOT NULL REFERENCES public.sets(id) ON DELETE CASCADE,
    market_date date NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','complete','failed')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error text,
    enqueued_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT price_storage_v2_shadow_queue_set_date_unique UNIQUE (set_id, market_date)
);

CREATE INDEX IF NOT EXISTS price_storage_v2_shadow_queue_pending_idx
    ON public.price_storage_v2_shadow_queue (status, market_date, id)
    WHERE status IN ('pending','failed');

ALTER TABLE public.price_storage_v2_shadow_queue ENABLE ROW LEVEL SECURITY;
