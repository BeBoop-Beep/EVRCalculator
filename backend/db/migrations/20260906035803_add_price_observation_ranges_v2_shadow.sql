CREATE TABLE IF NOT EXISTS public.card_variant_price_observation_ranges_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_variant_id uuid NOT NULL REFERENCES public.card_variants(id) ON DELETE CASCADE,
    condition_id uuid NOT NULL REFERENCES public.conditions(id),
    source text NOT NULL,
    currency text NOT NULL,
    observed_from date NOT NULL,
    observed_through date NOT NULL,
    observed_day_count integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT card_variant_price_observation_ranges_v2_valid_dates CHECK (observed_through >= observed_from),
    CONSTRAINT card_variant_price_observation_ranges_v2_positive_days CHECK (observed_day_count >= 1),
    CONSTRAINT card_variant_price_observation_ranges_v2_unique UNIQUE(card_variant_id,condition_id,source,currency,observed_from)
);

CREATE INDEX IF NOT EXISTS idx_cvpor_v2_variant_condition_range
ON public.card_variant_price_observation_ranges_v2(card_variant_id,condition_id,source,currency,observed_from,observed_through);

