CREATE OR REPLACE FUNCTION public.rebuild_card_variant_price_observation_ranges_v2_from_raw_scope(p_card_variant_ids uuid[])
RETURNS jsonb
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
DECLARE
    v_ranges bigint := 0;
BEGIN
    IF p_card_variant_ids IS NULL OR cardinality(p_card_variant_ids)=0 THEN
        RETURN jsonb_build_object('scopeVariants',0,'rangeRows',0);
    END IF;

    DELETE FROM public.card_variant_price_observation_ranges_v2 r
    WHERE r.card_variant_id=ANY(p_card_variant_ids);

    WITH observed_days AS MATERIALIZED (
        SELECT DISTINCT
            o.card_variant_id,
            o.condition_id,
            coalesce(nullif(trim(o.source),''),'UNKNOWN') AS source,
            coalesce(nullif(trim(both '"' from upper(trim(o.currency))),''),'USD') AS currency,
            o.captured_at AS observed_date
        FROM public.card_variant_price_observations o
        WHERE o.card_variant_id=ANY(p_card_variant_ids)
          AND o.captured_at IS NOT NULL
          AND o.market_price IS NOT NULL
          AND o.market_price>0
    ), flagged AS (
        SELECT d.*,
               CASE WHEN lag(d.observed_date) OVER w = d.observed_date - 1 THEN 0 ELSE 1 END AS new_range
        FROM observed_days d
        WINDOW w AS (
            PARTITION BY d.card_variant_id,d.condition_id,d.source,d.currency
            ORDER BY d.observed_date
        )
    ), grouped AS (
        SELECT f.*,
               sum(f.new_range) OVER (
                   PARTITION BY f.card_variant_id,f.condition_id,f.source,f.currency
                   ORDER BY f.observed_date
               ) AS range_group
        FROM flagged f
    )
    INSERT INTO public.card_variant_price_observation_ranges_v2(
        card_variant_id,condition_id,source,currency,
        observed_from,observed_through,observed_day_count
    )
    SELECT card_variant_id,condition_id,source,currency,
           min(observed_date),max(observed_date),count(*)::integer
    FROM grouped
    GROUP BY card_variant_id,condition_id,source,currency,range_group
    ORDER BY card_variant_id,condition_id,source,currency,min(observed_date);

    GET DIAGNOSTICS v_ranges=ROW_COUNT;
    RETURN jsonb_build_object('scopeVariants',cardinality(p_card_variant_ids),'rangeRows',v_ranges);
END;
$function$;

REVOKE ALL ON FUNCTION public.rebuild_card_variant_price_observation_ranges_v2_from_raw_scope(uuid[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.rebuild_card_variant_price_observation_ranges_v2_from_raw_scope(uuid[]) TO service_role;

